export function fillConsent(t: ConsentTemplate, p: Patient, ctx: { clinic: string; doctor: string }): string {
  const doctor = ctx.doctor ? `د. ${ctx.doctor.replace(/^د\.?\s*/, "")}` : "الطبيب المعالج";
  return t.text
    .replace(/\{name\}/g, p.name)
    .replace(/\{clinic\}/g, ctx.clinic || "العيادة")
    .replace(/\{doctor\}/g, doctor)
    .replace(/\{photoUse\}/g, "لا تُستعمل الصور لأي غرض آخر (كالنشر أو الإعلان) إلا بموافقة خطية مستقلة مني.");
}
